from contextlib import closing
from typing import Union, List, Dict, Optional
from pathlib import Path

import eccodes
import numpy as np
import xarray as xr
from tqdm import tqdm

from ._level import _fix_level
from ._check import _check_message
from ._lazy import lazy_values, concat_lazy_arrays
from ._xarray import create_data_array_from_message
from reki.readers.grib.common import MISSING_VALUE
from ._scan import iter_headers


def load_field_from_file(
        file_path: Union[str, Path],
        parameter: Union[str, Dict] = None,
        level_type: Union[str, Dict] = None,
        level: Union[int, float, List, Dict, str] = None,
        level_dim: Optional[str] = None,
        field_name: Optional[str] = None,
        show_progress: bool = False,
        lazy: bool = False,
        **kwargs
) -> Optional[xr.DataArray]:
    """
    Load **one** field from local GRIB2 file using eccodes-python.
    Or load multi levels into one field.

    Parameters
    ----------
    file_path : str or Path
    parameter : str or typing.Dict
        parameter name.

        Use GRIB key `shortName` or a dict of filter conditions such as:

        .. code-block::

            {
                "discipline": 0,
                "parameterCategory": 2,
                "parameterNumber": 225,
            }

    level_type : str or typing.Dict or None
        level type.

        - Use "pl", "ml" or "sfc". They will be converted into dict.
        - Use GRIB key `typeOfLevel`, such as
          "isobaricInhPa", "isobaricInPa", "surface", "heightAboveGround",
          "nominalTop", "atmosphere", "meanSea", "depthBelowLandLayer", ...
          See https://apps.ecmwf.int/codes/grib/format/edition-independent/3/ for more values.
        - If `typeOfLevel` is not available, use dict to specify filter conditions.
          For example, to get one filed from GRAPES GFS modelvar GRIB2 file, use:

          .. code-block::

            {
                "typeOfFirstFixedSurface": 131
            }

    level : int or float or typing.List or typing.Dict or None
        level value(s).

        - If use a scalar, level will be a non-dimension coordinate.
        - If your want to extract multi levels, use a list and level will be a dimension (level, lat, lon).
        - If use a dict, message will be filtered by dict keys. Support custom calculate keys:
            - ``first_level``
            - ``second_level``
        - If use `"all"`, all levels of level_type will be packed in the result field.
        - If use `None`, only the first field will be returned.

    level_dim : str or None
        name of level dimension.
        If none, function will generate a name for level dim.
        If `level_type="pl"`, some values can be used:

            - `None` or `pl` or `isobaricInhPa`: level_dim is a float number with unit hPa.
            - `isobaricInPa`: level_dim is a float number with unit Pa.

    field_name :
        name of field.

        * If ``None``, generate field name automatically.
            * use ``parameter`` if it's a string
            * use GRIB Key shortName if it's not `unknown`
            * use GRIB Keys to combine a name: `discipline_parameterCategory_parameterNumber`
        * If string, set the field's name with it.

    show_progress : bool
        show progress bar.

    lazy : bool
        if True, defer values decoding to data access: the file is
        scanned with ``headers_only=True`` (message data sections are
        skipped), coordinates and attributes are built immediately,
        and the returned ``DataArray`` wraps a lazy backend array
        holding only the file path and message offsets. ``isel`` /
        ``sel`` stay lazy; ``.values`` triggers decoding. Default
        False keeps the current immediate-decoding behavior.

    Returns
    -------
    DataArray or None:
        DataArray if found, or None if not.

    Examples
    --------
    Load 850hPa temperature field from a GRIB2 file generated by GRAPES GFS.

    .. code-block:: pycon

        >>> load_field_from_file(
        ...     file_path="/sstorage1/COMMONDATA/OPER/NWPC/GRAPES_GFS_GMF/Prod-grib/2020031721/ORIG/gmf.gra.2020031800105.grb2",
        ...     parameter="t",
        ...     level_type="isobaricInhPa",
        ...     level=850,
        ... )
        <xarray.DataArray 't' (latitude: 720, longitude: 1440)>
        array([[249.19234375, 249.16234375, 249.16234375, ..., 249.15234375,
                249.19234375, 249.14234375],
               [249.45234375, 249.45234375, 249.42234375, ..., 249.45234375,
                249.44234375, 249.44234375],
               [249.69234375, 249.68234375, 249.68234375, ..., 249.70234375,
                249.67234375, 249.68234375],
               ...,
               [235.33234375, 235.45234375, 235.62234375, ..., 235.47234375,
                235.63234375, 235.48234375],
               [235.78234375, 235.91234375, 235.64234375, ..., 235.80234375,
                235.72234375, 235.82234375],
               [235.66234375, 235.86234375, 235.82234375, ..., 235.85234375,
                235.68234375, 235.70234375]])
        Coordinates:
            time           datetime64[ns] 2020-03-18
            step           timedelta64[ns] 4 days 09:00:00
            valid_time     datetime64[ns] 2020-03-22T09:00:00
            isobaricInhPa  int64 850
          * latitude       (latitude) float64 89.88 89.62 89.38 ... -89.38 -89.62 -89.88
          * longitude      (longitude) float64 0.0 0.25 0.5 0.75 ... 359.2 359.5 359.8
        Attributes:
            GRIB_edition:                    2
            GRIB_centre:                     babj
            GRIB_subCentre:                  0
            GRIB_tablesVersion:              4
            GRIB_localTablesVersion:         1
            GRIB_dataType:                   fc
            GRIB_dataDate:                   20200318
            GRIB_dataTime:                   0
            GRIB_validityDate:               20200322
            GRIB_validityTime:               900
            GRIB_step:                       105
            GRIB_stepType:                   instant
            GRIB_stepUnits:                  1
            GRIB_stepRange:                  105
            GRIB_endStep:                    105
            GRIB_name:                       Temperature
            GRIB_shortName:                  t
            GRIB_cfName:                     air_temperature
            GRIB_discipline:                 0
            GRIB_parameterCategory:          0
            GRIB_parameterNumber:            0
            GRIB_gridType:                   regular_ll
            GRIB_gridDefinitionDescription:  Latitude/longitude
            GRIB_typeOfFirstFixedSurface:    pl
            GRIB_typeOfLevel:                isobaricInhPa
            GRIB_level:                      850
            GRIB_numberOfPoints:             1036800
            GRIB_missingValue:               9999
            GRIB_units:                      K
            long_name:                       Temperature
            units:                           K

    """
    from reki._legacy import check_engine, ignore_index, reader_errors

    check_engine(kwargs.pop("engine", "eccodes"))
    ignore_index(kwargs.pop("with_index", False))
    messages, offsets = [], []
    fixed_level_type, fixed_level_dim = _fix_level(level_type, level_dim)
    if field_name is None and isinstance(parameter, str):
        field_name = parameter
    try:
        with reader_errors(file_path, "load_field_from_file"), closing(iter_headers(file_path, headers_only=lazy)) as headers, tqdm(disable=not show_progress, unit="message") as progress:
            for header in headers:
                progress.update(1)
                if not _check_message(header.handle, parameter, fixed_level_type, level, **kwargs):
                    continue
                messages.append(header.detach())
                offsets.append(header.offset)
                if not (isinstance(level, list) or level == "all"):
                    break
            if not messages:
                return None
            arrays = []
            for message, offset in zip(messages, offsets):
                values = None
                if lazy:
                    shape = (eccodes.codes_get(message, "Nj"), eccodes.codes_get(message, "Ni"))
                    values = lazy_values(file_path, offset, shape, MISSING_VALUE, np.nan)
                arrays.append(create_data_array_from_message(
                    message, level_dim_name=fixed_level_dim, field_name=field_name, values=values,
                ))
            if len(arrays) == 1:
                return arrays[0]
            level_dim_name = fixed_level_dim or (level_type if isinstance(level_type, str) else None)
            if level_dim_name is None:
                level_dim_name = next(k for k in arrays[0].coords if k not in {"time", "step", "valid_time", "latitude", "longitude", "number"})
            if lazy:
                result = concat_lazy_arrays(arrays, level_dim_name)
                if result is not None:
                    return result
            return xr.concat(arrays, level_dim_name, coords="different", compat="equals")
    finally:
        for message in messages:
            eccodes.codes_release(message)



def load_field_from_files(file_list, parameter, level_type, level, level_dim=None,
                          show_progress=False, lazy=False, *,
                          include_report: bool = False, **kwargs):
    from .._legacy_collection import load_field_from_files as load_collection
    return load_collection(file_list, parameter, level_type, level,
                           level_dim=level_dim, show_progress=show_progress, lazy=lazy,
                           include_report=include_report, **kwargs)
